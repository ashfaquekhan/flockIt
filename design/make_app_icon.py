def svg_path(path):
    return " ".join("Z" if seg[0] == "Z" else seg[0] + " " + " ".join("%.2f,%.2f" % place(q, 1.0, 0.0) for q in seg[1:]) for seg in path)
open(os.path.join(HERE, "logo.svg"), "w", encoding="utf-8").write(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" width="512" height="512">\n'
    '  <rect width="200" height="200" rx="44" fill="#000000"/>\n' +
    "".join('  <path fill="%s" d="%s"/>\n' % (col, svg_path(pth)) for _, col, pth in PARTS) + '</svg>\n')

# ------------------------------------------------------------------ a preview of the loading animation (same steps as
# FlockLoader.kt): each part is moved into place whole — stem, top arm, middle arm, comb, beak, eye — held, cleared.
STEPS = {"stem": (0.00, 0.17, 0, 30), "top arm": (0.14, 0.31, 34, 0), "middle arm": (0.27, 0.44, 30, 0),
         "comb": (0.41, 0.56, 0, -24), "beak": (0.53, 0.66, -24, 0), "eye": (0.64, 0.74, 0, 0)}
FADE_FROM = 0.90


def shifted(path, dx, dy):
    return [seg if seg[0] == "Z" else (seg[0],) + tuple((x + dx, y + dy) for x, y in seg[1:]) for seg in path]


def loader_frame(p, px=220):
    ss = 3; n = px * ss
    im = Image.new("RGBA", (n, n), (0, 0, 0, 255))
    fade = 1 - (p - FADE_FROM) / (1 - FADE_FROM) if p > FADE_FROM else 1.0
    for name, col, path in PARTS:
        t0, t1, dx, dy = STEPS[name]
        t = min(1.0, max(0.0, (p - t0) / (t1 - t0)))
        if t <= 0: continue
        e = 1 - (1 - t) ** 3
        alpha = int(255 * min(1.0, t * 2.5) * fade)
        layer = Image.new("RGBA", (n, n), (0, 0, 0, 0)); dr = ImageDraw.Draw(layer)
        rgb = tuple(int(col[i:i + 2], 16) for i in (1, 3, 5))
        for pg in flatten(shifted(path, dx * (1 - e), dy * (1 - e)), n / 200, 0.0):
            dr.polygon(pg, fill=rgb + (alpha,))
        im = Image.alpha_composite(im, layer)
    return im.resize((px, px), Image.LANCZOS).convert("P", palette=Image.ADAPTIVE, colors=64)


frames = [loader_frame(i / 56) for i in range(57)]
frames[0].save(os.path.join(HERE, "loader-preview.gif"), save_all=True, append_images=frames[1:], duration=33, loop=0, disposal=2)
